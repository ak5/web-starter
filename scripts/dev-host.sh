#!/bin/bash
# Rewrite local dev URLs for a slot and emit .env.dev-slot. Local mode uses
# Caddy + namespaced localhost subdomains; tailnet mode binds apps directly to
# 0.0.0.0 so phones can reach them over Tailscale.

set -e

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PACKAGES=(api web admin)

usage() {
	echo "Usage:" >&2
	echo "  bash scripts/dev-host.sh local [<slot>]" >&2
	echo "  bash scripts/dev-host.sh tailscale <ip> [<slot>]" >&2
	exit 1
}

validate_slot() {
	if ! [[ "$1" =~ ^[1-9]$ ]]; then
		echo "Error: slot must be 1-9 (got: \"$1\")" >&2
		exit 1
	fi
}

MODE="${1:-}"
case "$MODE" in
	local)
		SLOT="${2:-1}"
		validate_slot "$SLOT"
		if [ "$SLOT" = "1" ]; then NS="ak5"; else NS="ak5${SLOT}"; fi
		SUFFIX="localhost"
		CADDY_BIND="127.0.0.1"
		IP=""
		;;
	tailscale)
		IP="${2:-}"
		SLOT="${3:-1}"
		if [ -z "$IP" ]; then
			echo "Error: tailscale mode requires an IP, e.g. \`pnpm dev:tailnet \$(tailscale ip -4 | head -1)\`" >&2
			exit 1
		fi
		if ! [[ "$IP" =~ ^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$ ]]; then
			echo "Error: \"$IP\" is not an IPv4 address. Pass the raw IP, not a hostname." >&2
			exit 1
		fi
		validate_slot "$SLOT"
		if [ "$SLOT" = "1" ]; then NS="ak5"; else NS="ak5${SLOT}"; fi
		SUFFIX="$IP"
		CADDY_BIND=""
		;;
	*)
		usage
		;;
esac

OFFSET=$(((SLOT - 1) * 10))
API_PORT=$((8350 + OFFSET))
WEB_PORT=$((8351 + OFFSET))
ADMIN_PORT=$((8352 + OFFSET))
EMAIL_PREVIEW_PORT=$((8354 + OFFSET))
EMAIL_MOCK_PORT=$((8355 + OFFSET))
CADDY_PORT=$((8359 + OFFSET))

if [ "$MODE" = "local" ]; then
	API_HOST="api.${NS}.${SUFFIX}"
	WEB_HOST="web.${NS}.${SUFFIX}"
	ADMIN_HOST="admin.${NS}.${SUFFIX}"
	MOCK_HOST="mock.${NS}.${SUFFIX}"
	PREVIEW_HOST="preview.${NS}.${SUFFIX}"
	COOKIE_ORIGIN_VALUE=".${NS}.${SUFFIX}"
else
	API_HOST="$IP"; WEB_HOST="$IP"; ADMIN_HOST="$IP"; MOCK_HOST="$IP"; PREVIEW_HOST="$IP"
	COOKIE_ORIGIN_VALUE="$IP"
fi

rewrite_kv() {
	local file="$1" key="$2" value="$3"
	[ -f "$file" ] || return 0
	awk -v k="$key" -v v="$value" '
		BEGIN { FS = "="; OFS = "=" }
		{ if ($0 ~ "^"k"=") { print k"="v; found = 1; next } print }
		END { if (!found) print k"="v }
	' "$file" > "$file.tmp"
	mv "$file.tmp" "$file"
}

url_for() {
	local host="$1" upstream_port="$2"
	if [ "$MODE" = "local" ]; then echo "http://${host}:${CADDY_PORT}"; else echo "http://${host}:${upstream_port}"; fi
}

for pkg in "${PACKAGES[@]}"; do
	ENV_FILE="$REPO_ROOT/packages/$pkg/.env"
	[ -f "$ENV_FILE" ] || continue
	rewrite_kv "$ENV_FILE" "PUBLIC_API_URL" "$(url_for "${API_HOST}" "${API_PORT}")"
	rewrite_kv "$ENV_FILE" "PUBLIC_APP_URL" "$(url_for "${WEB_HOST}" "${WEB_PORT}")"
	rewrite_kv "$ENV_FILE" "PUBLIC_ADMIN_URL" "$(url_for "${ADMIN_HOST}" "${ADMIN_PORT}")"
	rewrite_kv "$ENV_FILE" "EMAIL_MOCK_URL" "$(url_for "${MOCK_HOST}" "${EMAIL_MOCK_PORT}")"
	rewrite_kv "$ENV_FILE" "COOKIE_ORIGIN" "${COOKIE_ORIGIN_VALUE}"
	rewrite_kv "$ENV_FILE" "PUBLIC_COOKIE_ORIGIN" "${COOKIE_ORIGIN_VALUE}"
done

SLOT_FILE="$REPO_ROOT/.env.dev-slot"
cat > "$SLOT_FILE" <<EOF
# Auto-generated by scripts/dev-host.sh — do not edit by hand.
AK5_SLOT=${SLOT}
DEV_MODE=${MODE}
AK5_NS=${NS}
AK5_SUFFIX=${SUFFIX}
AK5_API_PORT=${API_PORT}
AK5_WEB_PORT=${WEB_PORT}
AK5_ADMIN_PORT=${ADMIN_PORT}
AK5_PREVIEW_PORT=${EMAIL_PREVIEW_PORT}
AK5_MOCK_PORT=${EMAIL_MOCK_PORT}
AK5_CADDY_PORT=${CADDY_PORT}
AK5_CADDY_BIND=${CADDY_BIND}
PUBLIC_API_URL=$(url_for "${API_HOST}" "${API_PORT}")
PUBLIC_WEB_URL=$(url_for "${WEB_HOST}" "${WEB_PORT}")
PUBLIC_ADMIN_URL=$(url_for "${ADMIN_HOST}" "${ADMIN_PORT}")
PUBLIC_COOKIE_ORIGIN=${COOKIE_ORIGIN_VALUE}
COOKIE_ORIGIN=${COOKIE_ORIGIN_VALUE}
AK5_API_URL=$(url_for "${API_HOST}" "${API_PORT}")
AK5_MOCK_URL=$(url_for "${MOCK_HOST}" "${EMAIL_MOCK_PORT}")
EOF

if [ "$MODE" = "local" ]; then
	echo "HMR_CLIENT_PORT=${CADDY_PORT}" >> "$SLOT_FILE"
fi

CADDY_DIR="$REPO_ROOT/.caddy"
CADDY_FILE="$CADDY_DIR/Caddyfile"
if [ "$MODE" = "local" ]; then
	mkdir -p "$CADDY_DIR"
	gen_block() {
		local host="$1" upstream="$2"
		cat <<EOF
http://${host}:${CADDY_PORT} {
	bind ${CADDY_BIND}
	reverse_proxy 127.0.0.1:${upstream}
}

EOF
	}
	{
		cat <<EOF
# Auto-generated by scripts/dev-host.sh — do not edit by hand.
{
	admin off
	persist_config off
	auto_https off
}

EOF
		gen_block "api.${NS}.${SUFFIX}" "${API_PORT}"
		gen_block "web.${NS}.${SUFFIX}" "${WEB_PORT}"
		gen_block "admin.${NS}.${SUFFIX}" "${ADMIN_PORT}"
		gen_block "mock.${NS}.${SUFFIX}" "${EMAIL_MOCK_PORT}"
		gen_block "preview.${NS}.${SUFFIX}" "${EMAIL_PREVIEW_PORT}"
	} > "$CADDY_FILE"
else
	rm -f "$CADDY_FILE"
fi

if [ "$MODE" = "local" ]; then
	echo "Slot ${SLOT} local (namespace ${NS}.${SUFFIX}). Caddy on :${CADDY_PORT} fronts every app:"
	echo "  web   -> http://web.${NS}.${SUFFIX}:${CADDY_PORT}"
	echo "  admin -> http://admin.${NS}.${SUFFIX}:${CADDY_PORT}"
	echo "  api   -> http://api.${NS}.${SUFFIX}:${CADDY_PORT}"
	echo "  email -> http://preview.${NS}.${SUFFIX}:${CADDY_PORT} (preview) / http://mock.${NS}.${SUFFIX}:${CADDY_PORT} (mock)"
else
	echo "Slot ${SLOT} tailnet (apps bind 0.0.0.0 on ${IP})."
	echo "  http://${IP}:${WEB_PORT} (web), :${ADMIN_PORT} (admin), :${API_PORT} (api)"
fi
